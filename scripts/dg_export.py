#!/usr/bin/env python3
"""
dg export: write the project's decisions as a Markdown decision log, ready for a README or a docs folder.

usage: dg export [--out FILE] [--project DIR] [--force]

Each decision in force gets a short record in the style of an architecture decision record: what was decided,
why, what was rejected, what it rests on, what rests on it, and what it replaced. Replaced decisions are listed
afterwards as history. Decisions you rejected as "not a decision" are left out.

By default it writes DECISIONS.md in the project folder. It only overwrites a file it wrote itself, unless you
pass --force.
"""
from __future__ import annotations

import argparse
import datetime as dt
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from dg_store import Graph, Store, id_num, project_dir, utf8_stdio  # noqa: E402

MARK = "<!-- generated by decision-graph: dg export -->"


def when(r: dict) -> str:
    raw = (r.get("source") or {}).get("decided_at") or r.get("extracted_at") or ""
    try:
        return dt.datetime.fromisoformat(raw.replace("Z", "+00:00")).strftime("%Y-%m-%d")
    except ValueError:
        return ""


def anchor(rid: str) -> str:
    return rid.lower()


def ref(g: Graph, rid: str) -> str:
    r = g.by_id.get(rid)
    return f"[{rid}](#{anchor(rid)})" + (f" ({r['decision']})" if r else "")


def status(g: Graph, rid: str) -> str:
    if g.stale_deps(rid):
        return "In force, but **stale**: something it rests on was replaced"
    if g.indirectly_stale(rid):
        return "In force, **indirectly affected**: something further up its chain was replaced"
    return "In force"


def render(project: Path, g: Graph) -> str:
    active = sorted(g.active(), key=lambda r: id_num(r["id"]))
    replaced = sorted((r for r in g.by_id.values() if not g.is_active(r["id"])), key=lambda r: id_num(r["id"]))
    dependents: dict[str, list[str]] = {}
    for r in g.by_id.values():
        for d in r.get("depends_on") or []:
            dependents.setdefault(d, []).append(r["id"])

    L = [MARK, f"# Decision log: {project.name}", ""]
    L.append(f"{len(active)} decisions in force, {len(replaced)} replaced along the way. "
             f"Recorded from the project's Claude Code conversations; generated {dt.date.today().isoformat()}.")
    stale = [r["id"] for r in active if g.stale_deps(r["id"]) or g.indirectly_stale(r["id"])]
    if stale:
        L.append(f"\n**Needs a look:** {', '.join(f'[{x}](#{anchor(x)})' for x in stale)} "
                 f"rest on decisions that were later replaced.")
    L += ["", "## Contents", ""]
    L += [f"- [{r['id']}](#{anchor(r['id'])}): {r['decision']}" for r in active]
    L += ["", "## Decisions in force", ""]
    for r in active:
        rid = r["id"]
        L.append(f"### {rid}")
        L.append(f"<a id=\"{anchor(rid)}\"></a>")
        L.append("")
        L.append(f"**{r['decision']}**")
        L.append("")
        who = "decided by the user" if r.get("decided_by") == "user" else "proposed by Claude, accepted by the user"
        meta = [status(g, rid), f"{when(r)}, {who}".strip(", ")]
        if r.get("confirmed"):
            meta.append("checked by the user")
        L.append("- **Status:** " + "; ".join(meta))
        reasons = [t for t, _ in g.rationale(rid)]
        if reasons:
            L.append("- **Why:** " + " ".join(x.rstrip(".") + "." for x in reasons))
        if r.get("alternatives_rejected"):
            L.append("- **Rejected:** " + "; ".join(r["alternatives_rejected"]))
        if r.get("depends_on"):
            L.append("- **Rests on:** " + "; ".join(ref(g, d) for d in r["depends_on"] if d in g.by_id))
        if dependents.get(rid):
            L.append("- **What rests on it:** " + ", ".join(f"[{d}](#{anchor(d)})" for d in sorted(dependents[rid], key=id_num)
                                                         if g.is_active(d)))
        chain = [x for x in g.history(rid) if x != rid]
        if chain:
            L.append("- **Replaced:** " + "; ".join(f"[{x}](#{anchor(x)}) ({when(g.by_id[x])}: {g.by_id[x]['decision']})"
                                                   for x in chain if x in g.by_id))
        for s, why in g.stale_deps(rid):
            L.append(f"- **Stale because:** it rests on {s}, which {why}")
        L.append("")
    if replaced:
        L += ["## Replaced decisions", "", "Earlier choices kept for the record, with what replaced them.", ""]
        for r in replaced:
            rid = r["id"]
            nxt = g.superseded_by.get(rid)
            L.append(f"- <a id=\"{anchor(rid)}\"></a>**{rid}** ({when(r)}): {r['decision']}"
                     + (f" Replaced by [{nxt}](#{anchor(nxt)})." if nxt else ""))
        L.append("")
    return "\n".join(L)


def main(argv=None) -> int:
    utf8_stdio()
    ap = argparse.ArgumentParser()
    ap.add_argument("--project", type=Path)
    ap.add_argument("--out", type=Path)
    ap.add_argument("--force", action="store_true")
    a = ap.parse_args(argv)
    project = (a.project or project_dir()).resolve()
    g = Graph(Store(project).records())
    if not g.by_id:
        print("No decisions recorded yet, so there's nothing to export.")
        return 1
    out = a.out or project / "DECISIONS.md"
    if out.exists() and not a.force and MARK not in out.read_text(encoding="utf-8", errors="replace")[:200]:
        print(f"{out} already exists and wasn't written by dg export. Use --out to pick another file, "
              f"or --force to overwrite it.")
        return 1
    out.write_text(render(project, g) + "\n", encoding="utf-8")
    print(f"Wrote {out}: {len(g.active())} decisions in force, "
          f"{sum(1 for r in g.by_id.values() if not g.is_active(r['id']))} replaced.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
